import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, readFile, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { HarborEngine } from '../src/engine/engine';
import { Transport } from '../src/engine/transport';
import type { Session } from '../src/shared/types';
import { cleanChatName, injectedChatName } from '../src/shared/chatName';

// What an older bridge reports for a Claude chat whose first turn was a slash command (truncated at 100 characters).
const caveat = '<local-command-caveat>Caveat: The messages below were generated by the user while running local comma';

test('names built from injected text are dropped, real text around them is kept', () => {
  assert.equal(cleanChatName(caveat), undefined);
  assert.equal(cleanChatName('<command-name>/model</command-name> <command-message>model</command-message> <command-args></command-args>'), undefined);
  assert.equal(cleanChatName('<environment_context> <cwd>/home/alice/project</cwd> </environment_context>'), undefined);
  assert.equal(cleanChatName('# AGENTS.md instructions for /home/alice/project <INSTRUCTIONS> Be brief.'), undefined);
  assert.equal(cleanChatName('[Request interrupted by user]'), undefined);
  assert.equal(cleanChatName('/clear'), undefined);
  assert.equal(cleanChatName(''), undefined);
  assert.equal(cleanChatName(undefined), undefined);
  assert.equal(cleanChatName('<system-reminder>be careful</system-reminder> Fix the login bug'), 'Fix the login bug');
  assert.equal(cleanChatName('Fix the <div> layout'), 'Fix the <div> layout');
  assert.equal(cleanChatName('/review the parser'), '/review the parser');
  assert.equal(cleanChatName('Refactor   the  parser'), 'Refactor the parser');
  assert.equal(injectedChatName(caveat), true);
  assert.equal(injectedChatName('Fix the login bug'), false);
});

test('automatic chat names saved from injected text are repaired on load; renamed ones are kept', async () => {
  const dir = await mkdtemp(path.join(tmpdir(), 'harbor-chat-names-'));
  const project = { id: 'p', name: 'P', cwd: '~', hostLabel: 'This Mac', connection: 'local', createdAt: '' };
  const chat = (id: string, name: string, extra: Partial<Session> = {}): Session => ({ id, tmuxName: `harbor-${id}`, paneId: '%0', name, host: 'local', cwd: '~', launcher: 'claude', command: 'claude', group: 'P', tags: [], pinned: false, archived: false, createdAt: '', updatedAt: '', status: 'closed', projectId: 'p', nameSource: 'auto', ...extra });
  const sessions = [chat('a1', caveat), chat('a2', '<system-reminder>x</system-reminder> Port the CLI', { launcher: 'codex' }), chat('a3', caveat, { nameSource: 'manual' }), chat('a4', 'Fix the login bug')];
  await writeFile(path.join(dir, 'sessions.json'), JSON.stringify({ version: 2, projects: [project], sessions }));
  const engine = new HarborEngine(dir, new Transport(`harbor-chat-names-${process.pid}`));
  try {
    const names = Object.fromEntries((await engine.init(false)).sessions.map(s => [s.id, s.name]));
    assert.deepEqual(names, { a1: 'Untitled chat', a2: 'Port the CLI', a3: caveat, a4: 'Fix the login bug' });
    assert.equal(JSON.parse(await readFile(path.join(dir, 'sessions.json'), 'utf8')).sessions.find((s: Session) => s.id === 'a1').name, 'Untitled chat');
  } finally { await engine.dispose(); }
});
